// Interactive map of the electricity demand data of the list. It draws
// map.geojson on a globe with a plain sea, so that every border and
// coastline comes from the same shapes and every area keeps its size; the
// globe flattens into the Web Mercator projection as it is zoomed in. Each
// place is coloured by the class of the years of data of every country and
// subdivision that covers it, and the outlines of all of them are drawn
// over the places, so that a subdivision inside another, or the earlier
// area of a grid, keeps its border. A click lists the data sources of every
// country and subdivision under it, the smallest first, from sources.json.
// Both files are generated by scripts/build.py next to this page, and the
// colours are those of map.css, in the reader's theme.

const CLASSES = 4;
const DARK = window.matchMedia("(prefers-color-scheme: dark)");

// The first view faces the Atlantic, and the globe, whose diameter is
// about 163 pixels at zoom 0 and doubles with each zoom level, fills most
// of the shorter side of the window.
function firstView() {
  const side = Math.min(window.innerWidth, window.innerHeight);
  return { center: [-15, 25], zoom: Math.log2((0.85 * side) / 163) };
}

function cssColour(name) {
  return getComputedStyle(document.documentElement)
    .getPropertyValue(name)
    .trim();
}

function fillColour() {
  const expression = ["match", ["get", "class"]];
  for (let i = 0; i < CLASSES; i += 1) {
    expression.push(i, cssColour(`--class-${i}`));
  }
  expression.push(cssColour("--land"));
  return expression;
}

const OUTLINES = ["==", ["get", "kind"], "outline"];
const COUNTRIES = ["all", OUTLINES, ["==", ["get", "subdivision"], null]];
const PLACES = ["==", ["get", "kind"], "place"];

function element(tag, text) {
  const node = document.createElement(tag);
  if (text) node.textContent = text;
  return node;
}

function link(text, url) {
  const node = element("a", text);
  node.href = url;
  node.target = "_blank";
  node.rel = "noopener";
  return node;
}

function seriesItem(series) {
  const item = element("li");
  item.append(link(series.source_name, series.url));
  const end = series.end === series.start ? "" : `-${series.end}`;
  item.append(` · ${series.start}${end} · ${series.resolution_minutes} min · `);
  item.append(link(series.licence_name, series.licence_url));
  if (series.access === "on-request") item.append(" · access on request");
  if (series.note) item.append(` · ${series.note}`);
  if (series.demandcast) item.append(" · retrieved by DemandCast");
  return item;
}

// The data sources of a country or subdivision, under its name.
function entitySection(country, subdivision) {
  const section = element("section");
  const series = country.series.filter(
    (s) => (s.subdivision_code ?? null) === subdivision,
  );
  const name = subdivision
    ? `${series[0]?.subdivision_name ?? subdivision}, ${country.name}`
    : country.name;
  section.append(element("h3", name));
  if (series.length === 0) {
    section.append(element("p", "No national data in the list yet."));
  } else {
    const list = element("ul");
    for (const s of series) list.append(seriesItem(s));
    section.append(list);
  }
  return section;
}

// The data sources of every country and subdivision under a click, the
// smallest first, as the place belongs to each of them. A country without
// national data is named only where none of its subdivisions has data.
function popupContent(list, features) {
  const content = element("div");
  const seen = new Set();
  const found = features
    .map((f) => f.properties)
    .filter((p) => list.countries[p.country])
    .filter((p) => {
      const key = `${p.country}-${p.subdivision ?? ""}`;
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    })
    .sort((a, b) => a.area - b.area);
  const national = (p) =>
    list.countries[p.country].series.some((s) => !s.subdivision_code);
  const entities =
    found.length > 1
      ? found.filter((p) => p.subdivision || national(p))
      : found;
  entities.forEach((p, i) => {
    if (i === 1) content.append(element("h4", "Also covering this place"));
    content.append(
      entitySection(list.countries[p.country], p.subdivision ?? null),
    );
  });
  return entities.length ? content : null;
}

const map = new maplibregl.Map({
  container: "map",
  style: {
    version: 8,
    projection: { type: "globe" },
    sources: {},
    layers: [
      {
        id: "sea",
        type: "background",
        paint: { "background-color": cssColour("--sea") },
      },
    ],
  },
  ...firstView(),
  minZoom: -1,
  maxZoom: 7,
  attributionControl: false,
});
map.addControl(new maplibregl.NavigationControl({ showCompass: false }));
map.addControl(
  new maplibregl.AttributionControl({
    compact: true,
    customAttribution:
      'Outlines: <a href="https://www.naturalearthdata.com/">Natural Earth</a>' +
      ' and <a href="https://github.com/open-energy-transition/demandcast">' +
      "DemandCast</a>",
  }),
);

function applyColours() {
  map.setPaintProperty("sea", "background-color", cssColour("--sea"));
  map.setPaintProperty("land", "fill-color", cssColour("--land"));
  map.setPaintProperty("places", "fill-color", fillColour());
  map.setPaintProperty("borders", "line-color", cssColour("--border"));
}

map.on("load", async () => {
  const [list, shapes] = await Promise.all([
    fetch("sources.json").then((response) => response.json()),
    fetch("map.geojson").then((response) => response.json()),
  ]);
  map.addSource("shapes", { type: "geojson", data: shapes });
  map.addLayer({
    id: "land",
    type: "fill",
    source: "shapes",
    filter: COUNTRIES,
    paint: { "fill-color": cssColour("--land") },
  });
  map.addLayer({
    id: "places",
    type: "fill",
    source: "shapes",
    filter: PLACES,
    paint: { "fill-color": fillColour() },
  });
  map.addLayer({
    id: "borders",
    type: "line",
    source: "shapes",
    filter: OUTLINES,
    paint: {
      "line-color": cssColour("--border"),
      "line-width": ["interpolate", ["linear"], ["zoom"], 1, 0.3, 6, 1],
    },
  });
  // The outlines again, unseen, to find every entity under the pointer.
  map.addLayer({
    id: "outlines",
    type: "fill",
    source: "shapes",
    filter: OUTLINES,
    paint: { "fill-opacity": 0 },
  });
  DARK.addEventListener("change", applyColours);

  const layers = ["outlines"];
  map.on("click", (event) => {
    const features = map.queryRenderedFeatures(event.point, { layers });
    const content = popupContent(list, features);
    if (!content) return;
    new maplibregl.Popup({ maxWidth: "420px" })
      .setLngLat(event.lngLat)
      .setDOMContent(content)
      .addTo(map);
  });
  map.on("mousemove", (event) => {
    const features = map.queryRenderedFeatures(event.point, { layers });
    const listed = features.some((f) => list.countries[f.properties.country]);
    map.getCanvas().style.cursor = listed ? "pointer" : "";
  });
});
